      let idx = 0;
      const line = y + vh * 0.45;
      for (let i = 0; i < tops.length; i++) if (tops[i] <= line) idx = i;
      if (idx !== curIdx) { curIdx = idx; setSection(idx); }

      // 히어로를 벗어나면 목차 등장
      const on = y > vh * 0.55;
